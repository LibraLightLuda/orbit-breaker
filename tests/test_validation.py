import copy
import math
from pathlib import Path
import sys
import tempfile
import unittest

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'tools'))
from prepare_combat_delivery import sha, source_hashes, validate_build, validate_performance


class PerformanceValidationTests(unittest.TestCase):
    def report(self, baseline=10.0, current=10.5):
        trial = {'p95_ms': baseline, 'samples': 300, 'min_enemies': 240, 'min_shots': 240, 'gems': 300}
        return {'baseline': [dict(trial) for _ in range(3)], 'current': [{**trial, 'p95_ms': current} for _ in range(3)], 'within_10_percent': True}

    def test_recomputes_result_instead_of_trusting_flag(self):
        report = self.report()
        report['within_10_percent'] = False
        report['p95_change_percent'] = 9999
        actual = validate_performance(report)
        self.assertTrue(actual['within_10_percent'])
        self.assertAlmostEqual(actual['p95_change_percent'], 5.0)
        self.assertFalse(report['within_10_percent'])

    def test_slow_measurements_fail_despite_true_flag(self):
        with self.assertRaises(ValueError):
            validate_performance(self.report(current=1000.0))

    def test_ten_percent_boundary(self):
        self.assertAlmostEqual(validate_performance(self.report(current=11.0))['p95_change_percent'], 10.0)
        with self.assertRaises(ValueError):
            validate_performance(self.report(current=11.001))

    def test_uses_median_across_trials(self):
        report = self.report()
        report['current'][2]['p95_ms'] = 1000.0
        self.assertAlmostEqual(validate_performance(report)['p95_change_percent'], 5.0)

    def test_invalid_measurements_fail(self):
        for value in [0, -1, math.nan, math.inf, True, '10']:
            with self.subTest(value=value), self.assertRaises(ValueError):
                report = self.report()
                report['baseline'][0]['p95_ms'] = value
                validate_performance(report)

    def test_missing_trials_or_load_fail(self):
        report = self.report()
        report['current'].pop()
        with self.assertRaises(ValueError):
            validate_performance(report)
        for key, value in [('samples', 299), ('min_enemies', 239), ('min_shots', 239), ('gems', 299), ('samples', math.nan), ('min_enemies', math.inf)]:
            with self.subTest(key=key), self.assertRaises(ValueError):
                report = self.report()
                report['current'][0][key] = value
                validate_performance(report)


class BuildSourceValidationTests(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory(prefix='orbit-validation-')
        self.addCleanup(self.temporary.cleanup)
        self.root = Path(self.temporary.name).resolve()
        for name in ['scripts/model.gd', 'assets/art.png', 'tests/check.gd', 'tools/check.py', 'tools/web_shell.html', 'project.godot', 'main.tscn', 'export_presets.cfg', 'icon.svg', 'build/candidate/OrbitBreaker.exe', 'build/candidate/web/index.pck', 'build/candidate/web/index.html']:
            path = self.root / name
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(name.encode())
        self.receipt = {'complete': True, 'source_hashes': source_hashes(self.root), 'outputs': {name: sha(self.root / 'build/candidate' / name) for name in ['OrbitBreaker.exe', 'web/index.pck', 'web/index.html']}}

    def test_unchanged_sources_and_outputs_pass(self):
        self.assertEqual(validate_build(self.receipt, self.root), self.receipt['source_hashes'])

    def test_runtime_and_validation_source_changes_fail(self):
        for name in ['scripts/model.gd', 'assets/art.png', 'tests/check.gd', 'tools/check.py', 'project.godot']:
            with self.subTest(name=name):
                path = self.root / name
                original = path.read_bytes()
                path.write_bytes(b'changed after tests')
                with self.assertRaises(ValueError):
                    validate_build(self.receipt, self.root)
                path.write_bytes(original)

    def test_added_or_removed_source_fails(self):
        path = self.root / 'scripts/new.gd'
        path.write_bytes(b'new source')
        with self.assertRaises(ValueError):
            validate_build(self.receipt, self.root)
        path.unlink()
        (self.root / 'scripts/model.gd').unlink()
        with self.assertRaises(ValueError):
            validate_build(self.receipt, self.root)

    def test_generated_uid_and_bytecode_do_not_invalidate_sources(self):
        (self.root / 'scripts/model.gd.uid').write_bytes(b'generated uid')
        (self.root / 'tools/check.pyc').write_bytes(b'generated bytecode')
        validate_build(self.receipt, self.root)

    def test_changed_export_fails(self):
        for name in self.receipt['outputs']:
            with self.subTest(name=name):
                path = self.root / 'build/candidate' / name
                original = path.read_bytes()
                path.write_bytes(b'changed export')
                with self.assertRaises(ValueError):
                    validate_build(self.receipt, self.root)
                path.write_bytes(original)

    def test_incomplete_receipt_or_missing_required_output_fails(self):
        receipt = copy.deepcopy(self.receipt)
        receipt['complete'] = False
        with self.assertRaises(ValueError):
            validate_build(receipt, self.root)
        receipt = copy.deepcopy(self.receipt)
        del receipt['outputs']['web/index.pck']
        with self.assertRaises(ValueError):
            validate_build(receipt, self.root)

    def test_output_path_cannot_escape_candidate(self):
        self.receipt['outputs']['../outside.exe'] = 'untrusted'
        with self.assertRaises(ValueError):
            validate_build(self.receipt, self.root)


if __name__ == '__main__':
    unittest.main()
